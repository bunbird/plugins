#!/usr/bin/env node
// Generates every client package from canonical/. Node >= 20, no dependencies.
//   node scripts/build.mjs          write everything
//   node scripts/build.mjs --check  regenerate in memory, fail on any drift
import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync, readdirSync, statSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8");
const facts = JSON.parse(read("canonical/facts.json"));
const bin = (p) => readFileSync(join(root, p));
const iconPng = bin("canonical/assets/icon-512.png");
const iconSvg = bin("canonical/assets/icon.svg");
const skillBody = read("canonical/skill.md").trimEnd();
const note = (client) =>
  existsSync(join(root, `canonical/platform-notes/${client}.md`))
    ? read(`canonical/platform-notes/${client}.md`).trimEnd()
    : "";

// Directories owned entirely by the generator: anything in them not produced here is drift.
const GENERATED_DIRS = ["plugins"];

const { product, servers, urls, marketplace } = facts;
const server = servers.bunbird;
const vars = {
  name: server.name,
  url: server.url,
  llms: urls.llms,
  llmsFull: urls.llmsFull,
  agentSkills: urls.agentSkills,
};
const fill = (s) =>
  s.replace(/\{\{(\w+)\}\}/g, (_, k) => {
    if (!(k in vars)) throw new Error(`unknown placeholder {{${k}}}`);
    return vars[k];
  });

const json = (o) => JSON.stringify(o, null, 2) + "\n";
const BANNER = "<!-- Generated by scripts/build.mjs from canonical/. Do not edit. -->";
const author = { name: product.publisher.name, url: product.publisher.url };

const skillDescription =
  "Build, preview and publish small web apps with Bunbird, a hosted platform driven through one MCP connector (bunbird). Use when the person wants an app, tool, tracker or form built and hosted, or mentions Bunbird.";
const skillFileAs = (name) => `---
name: ${name}
description: ${skillDescription}
---

${BANNER}

# ${product.name}

${fill(skillBody)}
`;
const skillFile = skillFileAs(product.slug);

const ruleFile = `---
description: Build, preview and publish a small hosted web app with Bunbird. Use when the person wants an app, tool, tracker or form that outlives the chat.
globs:
alwaysApply: false
---

${BANNER}

# ${product.name}

${fill(skillBody)}
`;

const contextFile = (title, extra) => `${BANNER}

# ${title}

${product.longDescription}

${fill(skillBody)}
${extra ? `\n## Connecting\n\n${fill(extra)}\n` : ""}`;

const clients = {
  "claude-code": { label: "Claude Code and GitHub Copilot", install: ["/plugin marketplace add bunbird/plugins", "/plugin install bunbird@bunbird"] },
  codex: { label: "Codex", install: ["codex plugin marketplace add bunbird/plugins", "codex plugin add bunbird@bunbird"] },
  antigravity: { label: "Antigravity", install: ["git clone https://github.com/bunbird/plugins.git", "agy plugin install plugins/plugins/antigravity/bunbird"] },
  cursor: { label: "Cursor", install: ["git clone https://github.com/bunbird/plugins.git", "mkdir -p ~/.cursor/plugins/local", "cp -R plugins/plugins/cursor/bunbird ~/.cursor/plugins/local/bunbird"] },
};
const pluginReadme = (id) => {
  const c = clients[id];
  const n = note(id);
  return `${BANNER}

# ${product.name} for ${c.label}

${product.packageDescription}

## Install

\`\`\`
${c.install.join("\n")}
\`\`\`

The plugin carries the connector, but you must accept it after install.
${n ? "\n" + fill(n) + "\n" : ""}
## Connector

| Connector | URL | Auth |
|---|---|---|
| \`${server.name}\` | ${server.url} | OAuth |

${server.summary}
`;
};

const files = new Map();
const put = (p, c) => files.set(p, c);

// Claude Code. No `version` anywhere: it would pin the plugin, and commits would ship nothing.
{
  const base = "plugins/claude-code/bunbird";
  put(`${base}/.claude-plugin/plugin.json`, json({
    name: product.slug,
    description: product.packageDescription,
    author,
    homepage: urls.website,
    repository: urls.repository,
    privacyPolicyUrl: urls.privacy,
    keywords: product.keywords,
    icon: "./assets/icon.png",
  }));
  put(`${base}/assets/icon.png`, iconPng);
  put(`${base}/.mcp.json`, json({
    mcpServers: {
      [server.name]: { type: "http", url: server.url },
    },
  }));
  put(`${base}/skills/${product.slug}/SKILL.md`, skillFile);
  put(`${base}/README.md`, pluginReadme("claude-code"));
}

// Codex.
{
  const base = "plugins/codex/bunbird";
  put(`${base}/.codex-plugin/plugin.json`, json({
    name: product.slug,
    version: facts.version,
    description: product.packageDescription,
    author,
    homepage: urls.website,
    repository: urls.repository,
    keywords: product.keywords,
    skills: "./skills/",
    mcpServers: "./.mcp.json",
    interface: {
      displayName: product.name,
      shortDescription: product.shortDescription,
      longDescription: product.longDescription,
      developerName: product.publisher.name,
      category: product.category,
      capabilities: ["Interactive", "Write"],
      websiteURL: urls.website,
      defaultPrompt: facts.defaultPrompts,
      composerIcon: "./assets/icon.png",
      logo: "./assets/icon.png",
    },
  }));
  put(`${base}/assets/icon.png`, iconPng);
  put(`${base}/.mcp.json`, json({
    mcpServers: {
      [server.name]: { url: server.url },
    },
  }));
  put(`${base}/skills/${product.slug}/SKILL.md`, skillFile);
  put(`${base}/README.md`, pluginReadme("codex"));
}

// Cursor.
{
  const base = "plugins/cursor/bunbird";
  put(`${base}/.cursor-plugin/plugin.json`, json({
    name: product.slug,
    description: product.packageDescription,
    author,
    keywords: product.keywords,
    logo: "assets/icon.svg",
  }));
  put(`${base}/assets/icon.svg`, iconSvg);
  put(`${base}/mcp.json`, json({
    mcpServers: {
      [server.name]: { url: server.url },
    },
  }));
  put(`${base}/rules/${product.slug}.mdc`, ruleFile);
  put(`${base}/skills/${product.slug}/SKILL.md`, skillFile);
  put(`${base}/README.md`, pluginReadme("cursor"));
}

// OpenAI directory submission package (Agent Plugins format). Zip the folder contents:
//   cd plugins/openai/bunbird && zip -r ../bunbird-openai.zip .
// Refs: https://developers.openai.com/plugins/deploy/submission
//       https://developers.openai.com/plugins/build/plugins
{
  const base = "plugins/openai/bunbird";
  const limit = (label, v, max) => {
    if (v.length > max) throw new Error(`openai ${label} is ${v.length} chars, max ${max}`);
    return v;
  };
  const review = JSON.parse(read("canonical/openai-review.json"));
  const tc = review.test_cases ?? {};
  const hasCases = (tc.positive?.length ?? 0) + (tc.negative?.length ?? 0) > 0;
  if (hasCases && (tc.positive.length !== 5 || tc.negative.length !== 3))
    throw new Error("openai review needs exactly 5 positive and 3 negative test cases");
  const reviewOut = {};
  if (hasCases) reviewOut.test_cases = { positive: tc.positive, negative: tc.negative };
  if (review.demo_recording_url) reviewOut.demo_recording_url = review.demo_recording_url;
  reviewOut.commerce = facts.openai.commerce;
  reviewOut.commerce_description = facts.openai.commerceDescription;
  put(`${base}/plugin.json`, json({
    $schema: "https://agent-plugins.org/schemas/1.0.0/plugin.schema.json",
    name: product.slug,
    version: facts.version,
    description: product.packageDescription,
    author,
    homepage: urls.website,
    repository: urls.repository,
    license: "MIT",
    keywords: product.keywords,
    extensions: {
      "com.openai": {
        interface: {
          displayName: limit("displayName", product.name, 30),
          shortDescription: limit("shortDescription", product.shortDescription, 30),
          longDescription: limit("longDescription", product.longDescription, 4000),
          developerName: limit("developerName", product.publisher.name, 80),
          category: product.category,
          capabilities: facts.openai.capabilities,
          websiteURL: urls.website,
          supportURL: urls.support,
          privacyPolicyURL: urls.privacy,
          termsOfServiceURL: urls.terms,
          defaultPrompt: facts.defaultPrompts.map((p) => limit("defaultPrompt", p, 128)),
          composerIcon: "./assets/icon.png",
          logo: "./assets/icon.png",
        },
        onboardingSkill: "./skills/get-started/SKILL.md",
        review: reviewOut,
        publication: { release_notes: facts.openai.releaseNotes },
      },
    },
  }));
  put(`${base}/mcp.json`, json({
    $schema: "https://agent-plugins.org/schemas/1.0.0/mcp.schema.json",
    mcpServers: {
      [server.name]: {
        type: "streamable-http",
        url: server.url,
        extensions: { "com.openai": { auth: { type: "oauth", client: { mode: "dcr" } } } },
      },
    },
  }));
  put(`${base}/skills/get-started/SKILL.md`, skillFileAs("get-started"));
  put(`${base}/assets/icon.png`, iconPng);
}

// Antigravity: agy plugin validate --strict rejects the repository root, whose AGENTS.md and GEMINI.md it never loads.
{
  const d = product.marketplaceDescription;
  if (d.length < 120 || d.length > 160)
    throw new Error(`antigravity description is ${d.length} chars, recommended 120-160`);
  const base = `plugins/antigravity/${product.slug}`;
  put(`${base}/plugin.json`, json({
    $schema: "https://antigravity.google/schemas/v1/plugin.json",
    name: product.slug,
    displayName: product.name,
    description: d,
    version: facts.version,
    logo: "assets/icon.png",
    suggestedPrompts: facts.defaultPrompts.slice(0, 3),
    author,
    homepage: urls.website,
    license: "MIT",
  }));
  put(`${base}/assets/icon.png`, iconPng);
  put(`${base}/mcp_config.json`, json({
    mcpServers: {
      [server.name]: { serverUrl: server.url },
    },
  }));
  put(`${base}/skills/${product.slug}/SKILL.md`, skillFile);
  put(`${base}/README.md`, pluginReadme("antigravity"));
}

// Marketplaces. Plugin versions live in plugin manifests only, never here.
put(".claude-plugin/marketplace.json", json({
  name: marketplace.name,
  owner: marketplace.owner,
  description: product.packageDescription,
  plugins: [{
    name: product.slug,
    source: "./plugins/claude-code/bunbird",
    description: product.packageDescription,
    author,
    homepage: urls.website,
    category: product.category,
    keywords: product.keywords,
  }],
}));
put(".agents/plugins/marketplace.json", json({
  name: marketplace.name,
  interface: { displayName: marketplace.displayName },
  plugins: [{
    name: product.slug,
    source: { source: "local", path: "./plugins/codex/bunbird" },
    policy: { installation: "AVAILABLE", authentication: "ON_INSTALL" },
    category: product.category,
  }],
}));
put(".cursor-plugin/marketplace.json", json({
  name: marketplace.name,
  owner: marketplace.owner,
  metadata: { description: product.packageDescription },
  plugins: [{
    name: product.slug,
    source: "./plugins/cursor/bunbird",
    description: product.packageDescription,
  }],
}));

// Gemini CLI.
put("gemini-extension.json", json({
  name: product.slug,
  version: facts.version,
  description: product.packageDescription,
  contextFileName: "GEMINI.md",
  mcpServers: {
    [server.name]: { httpUrl: server.url },
  },
}));
put("GEMINI.md", contextFile(`${product.name} (Gemini CLI)`, note("gemini")));

// Root skill and agent instructions for any tool that reads them.
put("SKILL.md", skillFile);
put("AGENTS.md", contextFile("AGENTS.md", `Connect the MCP server \`${server.name}\` at ${server.url} (OAuth, you sign in when you connect). Per-client plugins are in this repository.`));

// .gitattributes marks every generated JSON path; markdown carries its own banner.
const generatedJson = [...files.keys()].filter((p) => p.endsWith(".json") && !p.startsWith("plugins/")).sort();
put(".gitattributes", [
  "# Generated from canonical/ by scripts/build.mjs. Edit canonical/, not these.",
  "plugins/** linguist-generated=true",
  ...generatedJson.map((p) => `${p} linguist-generated=true`),
  "SKILL.md linguist-generated=true",
  "AGENTS.md linguist-generated=true",
  "GEMINI.md linguist-generated=true",
  "",
].join("\n"));

const walk = (dir) => {
  const out = [];
  if (!existsSync(dir)) return out;
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else out.push(relative(root, full).split(sep).join("/"));
  }
  return out;
};
const onDisk = () => GENERATED_DIRS.flatMap((d) => walk(join(root, d)));

if (process.argv.includes("--check")) {
  const problems = [];
  for (const [p, c] of files) {
    const full = join(root, p);
    if (!existsSync(full)) problems.push(`missing: ${p}`);
    else if (!readFileSync(full).equals(Buffer.from(c))) problems.push(`drift: ${p}`);
  }
  for (const p of onDisk()) if (!files.has(p)) problems.push(`extra: ${p}`);
  if (problems.length) {
    console.error(problems.join("\n"));
    console.error(`\n${problems.length} problem(s). Run: node scripts/build.mjs`);
    process.exit(1);
  }
  console.log(`ok: ${files.size} generated files match canonical/`);
} else {
  for (const p of onDisk()) if (!files.has(p)) rmSync(join(root, p));
  for (const [p, c] of files) {
    mkdirSync(dirname(join(root, p)), { recursive: true });
    writeFileSync(join(root, p), c);
  }
  console.log(`wrote ${files.size} files`);
}
